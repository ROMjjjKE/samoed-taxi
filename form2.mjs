import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 900 });
await p.goto('http://127.0.0.1:4300/samoed-taxi/', { waitUntil: 'networkidle2' });
await p.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; window.__opened = null; window.open = (u) => { window.__opened = u; return null; }; });
await p.evaluate(() => document.fonts.ready);
await p.evaluate(() => document.querySelector('#zayavka').scrollIntoView());
await new Promise(r => setTimeout(r, 400));
await p.type('#from', 'Пинск, ул. Ленина 12');
await p.type('#phone', '+375 33 111-22-33');
await p.evaluate(() => { document.querySelectorAll('.seg label')[1].click(); });
await new Promise(r => setTimeout(r, 250));
const disabled = await p.evaluate(() => document.querySelector('#time').disabled);
await p.evaluate(() => { const t = document.querySelector('#time'); t.focus(); });
await p.type('#time', '07:30');
await new Promise(r => setTimeout(r, 250));
console.log('time disabled after radio:', disabled);
console.log('draft when:', await p.evaluate(() => [...document.querySelectorAll('.copy__row')][2].innerText.replace(/\n/g, ': ')));
await p.click('form.form button[type=submit]');
await new Promise(r => setTimeout(r, 300));
console.log('opened:', decodeURIComponent((await p.evaluate(() => window.__opened)) || '').split('?text=')[1]?.replace(/\+/g, ' ').slice(0, 200));
console.log('status:', await p.evaluate(() => document.querySelector('[role=status]').textContent));
await b.close();
