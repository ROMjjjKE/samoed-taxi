import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'], protocolTimeout: 60000 });
const p = await b.newPage();
await p.setViewport({ width: 1200, height: 630 });
await p.goto('https://romjjjke.github.io/samoed-taxi/', { waitUntil: 'networkidle2' });
await p.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 900));
await p.screenshot({ path: 'public/og.jpg', type: 'jpeg', quality: 86 });
console.log('og ok');
await b.close();
