import puppeteer from 'puppeteer-core';
const URL = 'https://romjjjke.github.io/samoed-taxi/';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const errs = [];
const d = await b.newPage();
d.on('pageerror', e => errs.push(e.message));
await d.setViewport({ width: 1440, height: 900 });
await d.goto(URL, { waitUntil: 'networkidle2' });
await d.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; });
await d.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 900));
const shot = async (page, sel, name, off = 0) => {
  await page.evaluate(y => window.scrollTo({ top: y, behavior: 'instant' }), sel ? await page.evaluate(s => Math.round(document.querySelector(s).getBoundingClientRect().top + window.scrollY + 0), sel) + off : 0);
  await new Promise(r => setTimeout(r, 700));
  await page.screenshot({ path: `screenshots/${name}.png` });
};
await d.screenshot({ path: 'screenshots/desktop-1440.png' });
await shot(d, '#talon', 'desktop-talon', 200);
await shot(d, '#poezdki', 'desktop-poezdki');
await shot(d, '#zayavka', 'desktop-zayavka', -40);
await shot(d, '#voprosy', 'desktop-voprosy');
await shot(d, '#kontakty', 'desktop-kontakty');
const m = await b.newPage();
await m.setViewport({ width: 390, height: 844, deviceScaleFactor: 2 });
await m.goto(URL, { waitUntil: 'networkidle2' });
await m.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; });
await m.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 900));
await m.screenshot({ path: 'screenshots/mobile-390.png' });
await shot(m, '#talon', 'mobile-390-talon', 60);
await shot(m, '#zayavka', 'mobile-390-zayavka', 40);
await shot(m, '#voprosy', 'mobile-390-voprosy', 40);
const o = await d.screenshot({ encoding: 'base64', clip: { x: 0, y: 0, width: 1200, height: 630 } });
const fs = await import('node:fs');
fs.writeFileSync('public/og.jpg', Buffer.from(o, 'base64'));
console.log('shots ok', errs);
await b.close();
